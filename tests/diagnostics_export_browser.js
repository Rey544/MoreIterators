(async()=>{
 let checks=0;
 const assert=(value,message)=>{checks++;if(!value)throw Error(message);};
 const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
 try{
  await MI18n.ready;
  const dialog=document.querySelector('.mi-diagnostics'),source=dialog.querySelector('select');
  const download=dialog.querySelector('.tools button'),close=dialog.querySelector('.tools button:last-child');
  const entry=[...document.querySelectorAll('header button')].find(button=>button.textContent===MI18n.t('ui.exportLog'));
  const open=async()=>{await entry.onclick();await tick();};
  const change=async value=>{source.value=value;await source.onchange();await tick();};
  for(const language of ['zh-CN','en']){
   MI18n.setLocale(language,false);await tick();await open();
   assert(dialog.open&&source.value==='editor','Editor log is not the default');
   assert(source.getAttribute('aria-label')===MI18n.t('diagnostics.source'),'Source label is not translated');
   assert(source.options[0].text===MI18n.t('diagnostics.editor')&&source.options[1].text===MI18n.t('diagnostics.game'),'Source options are not translated');
   assert(dialog.querySelector('p[data-i18n-content]').textContent.includes('/保存/'),'Log path was translated');
   assert(dialog.querySelectorAll('pre')[1].textContent.endsWith('\n保存'),'Log content was translated');
   assert(!download.disabled,'Editor log cannot be exported');
   await download.onclick();await tick();
   assert(diagnosticsDownloads.at(-1).name==='studio-errors.log','Wrong editor filename');
   assert(await diagnosticsDownloads.at(-1).data.text()===fullEditorLog,'Only the editor preview tail was exported');
   assert(diagnosticsDownloads.at(-1).data.size>131072,'Full editor log fixture is too small');
   await change('game');await download.onclick();await tick();
   assert(diagnosticsDownloads.at(-1).name==='LogOutput.txt','Wrong game filename: '+JSON.stringify({names:diagnosticsDownloads.map(item=>item.name),source:source.value,disabled:download.disabled,calls:diagnosticsCalls.slice(-4),state:dialog.textContent}));
   assert(await diagnosticsDownloads.at(-1).data.text()===fullGameLog,'Only the game preview tail was exported');
   editorState='no-preview';await change('editor');
   assert(!download.disabled,'An empty tail blocked the full log download');
   await download.onclick();
   assert(await diagnosticsDownloads.at(-1).data.text()===fullEditorLog,'A log without a preview was not fully exported');
   editorState='missing';await change('editor');
   assert(download.disabled&&dialog.textContent.includes(MI18n.t('diagnostics.editorUnavailable')),'Missing editor log did not disable export');
   const before=diagnosticsDownloads.length;await download.onclick();
   assert(diagnosticsDownloads.length===before,'Missing editor log made an empty download');
   editorState='error';await change('game');await change('editor');
   assert(download.disabled&&dialog.textContent.includes(MI18n.t('diagnostics.readFailed')),'Preview failure is not localized');
   editorState='ok';await change('editor');downloadState='error';await download.onclick();await tick();
   assert(dialog.open&&!download.disabled&&!source.disabled,'Download failure blocked the dialog');
   assert(dialog.textContent.includes(MI18n.t('diagnostics.readFailed')),'Download failure is not localized');
   MI18n.setLocale(language==='en'?'zh-CN':'en',false);await tick();
   assert(dialog.textContent.includes(MI18n.t('diagnostics.readFailed')),'Open error details did not follow language changes');
   MI18n.setLocale(language,false);await tick();
   downloadState='ok';await download.onclick();await tick();
   assert(diagnosticsDownloads.length===before+1,'Download could not be retried');
   downloadState='missing';await download.onclick();await tick();
   assert(dialog.textContent.includes(MI18n.t('diagnostics.editorUnavailable')),'Missing download is not localized');
   downloadState='empty';await download.onclick();await tick();
   assert(download.disabled&&diagnosticsDownloads.length===before+1,'An empty file was downloaded');
   downloadState='ok';close.click();await tick();
  }
  await open();
  const previewWait=holdPreview=deferred();source.value='editor';const stale=source.onchange();await tick();
  await change('game');previewWait.resolve();await stale;await tick();
  assert(source.value==='game'&&dialog.querySelectorAll('pre')[1].textContent===previewFor('game').tail,'Stale editor preview replaced game log');
  await download.onclick();
  assert(diagnosticsDownloads.at(-1).name==='LogOutput.txt','Stale preview changed the download source');
  const exportWait=holdDownload=deferred(),beforeClose=diagnosticsDownloads.length;
  const inFlight=download.onclick();await tick();
  assert(download.disabled&&source.disabled,'Downloading controls are not disabled');
  close.click();await tick();await open();
  assert(source.value==='editor'&&!source.disabled&&!download.disabled,'Reopening did not recover controls');
  await download.onclick();
  assert(diagnosticsDownloads.at(-1).name==='studio-errors.log','Reopened editor download failed');
  exportWait.resolve();await inFlight;await tick();
  assert(diagnosticsDownloads.length===beforeClose+1,'Closed dialog emitted a stale download');
  assert(!diagnosticsErrors.length,'Browser errors: '+diagnosticsErrors.join('\n'));
  assert(!MI18n.missing.length,'Missing translations: '+MI18n.missing.join('\n'));
  document.getElementById('result').textContent=JSON.stringify({ok:true,checks,downloads:diagnosticsDownloads.length});
 }catch(error){document.getElementById('result').textContent=JSON.stringify({ok:false,checks,error:error.stack,errors:diagnosticsErrors});}
})();
